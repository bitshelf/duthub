#!/usr/bin/perl
# 从 duthub.html 的 SVG sprite 生成 apps/desktop/src/icons_gen.rs（1:1 图标移植）。
# 同时生成 src/i18n_gen.rs（zh/en 93 键）。
use strict;
use warnings;

my $root = $0 =~ s{/[^/]*$}{}r eq $0 ? '.' : $0 =~ s{/[^/]*$}{}r;
my $html_file = "$root/../docs/duthub.html";
my $out_dir = "$root/../apps/desktop/src";

open my $fh, '<', $html_file or die "cannot open $html_file: $!";
my @lines = <$fh>;
close $fh;
my $html = join('', @lines);

# ---- 图标 ----
my @icons;
while ($html =~ /<symbol id="i-([a-z0-9-]+)" viewBox="0 0 24 24">(.*?)<\/symbol>/gs) {
    my ($name, $inner) = ($1, $2);
    $inner =~ s/\s+/ /g;
    $inner =~ s/^ //;
    $inner =~ s/ $//;
    push @icons, [$name, $inner];
}
die "未解析到图标" unless @icons >= 40;

{
    open my $out, '>', "$out_dir/icons_gen.rs" or die $!;
    print $out "// GENERATED by scripts/gen-icons.pl — 从 duthub.html sprite 1:1 提取，勿手改。\n";
    print $out "pub static ICONS: &[(&str, &str)] = &[\n";
    for my $icon (@icons) {
        my ($name, $inner) = @$icon;
        my $doc = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"#000\" stroke-width=\"1.8\" stroke-linecap=\"round\" stroke-linejoin=\"round\">$inner</svg>";
        print $out "    (r#\"$name\"#, r##\"$doc\"##),\n";
    }
    print $out "];\n";
    close $out;
}

# ---- i18n ----
sub strip_close {
    my $s = shift;
    $s =~ s/[};,]\s*$// while $s =~ /[};,]\s*$/;
    return $s;
}
sub js_unescape {
    my $s = shift;
    $s =~ s/\\'/'/g;
    $s =~ s/\\"/"/g;
    $s =~ s/\\n/\n/g;
    $s =~ s/\\\\/\\/g;
    return $s;
}
sub extract_kv {
    my ($body) = @_;
    my %out;
    while ($body =~ /([A-Za-z0-9]+):'((?:\\.|[^'\\])*)'/g) {
        $out{$1} = js_unescape($2);
    }
    return \%out;
}

my ($zh_body, $en_body);
for my $line (@lines) {
    if ($line =~ /^\s*'zh-CN':\{(.+)$/) { $zh_body = strip_close($1); }
    elsif ($line =~ /^\s*'en-US':\{(.+)$/) { $en_body = strip_close($1); }
}
die "未找到 i18n 块" unless defined $zh_body && defined $en_body;
my $zh = extract_kv($zh_body);
my $en = extract_kv($en_body);
my @missing_en = grep { !exists $en->{$_} } sort keys %$zh;
my @missing_zh = grep { !exists $zh->{$_} } sort keys %$en;
die "i18n 键不一致" if @missing_en || @missing_zh;

{
    open my $out, '>', "$out_dir/i18n_gen.rs" or die $!;
    print $out "// GENERATED by scripts/gen-icons.pl — 从 duthub.html i18n 表 1:1 提取（key, zh-CN, en-US），勿手改。\n";
    print $out "pub static I18N: &[(&str, &str, &str)] = &[\n";
    for my $k (sort keys %$zh) {
        my ($z, $e) = ($zh->{$k}, $en->{$k});
        for my $v ($z, $e) { die "值包含 \"##\" 冲突: $k" if $v =~ /"\#\#/; }
        print $out "    (r#\"$k\"#, r##\"$zh->{$k}\"##, r##\"$en->{$k}\"##),\n";
    }
    print $out "];\n";
    close $out;
}

printf "OK: icons=%d i18n=%d\n", scalar(@icons), scalar(keys %$zh);
